    @Test
    void testEncryptedValueObjectContracts() {
        EncryptedText text1 = EncryptedText.of("hello");
        EncryptedText text2 = EncryptedText.of("hello");
        EncryptedText text3 = EncryptedText.of("world");

        assertThat(text1)
                .isNotNull()
                .isEqualTo(text2)
                .isNotEqualTo(text3)
                .hasSameHashCodeAs(text2)
                .hasToString("EncryptedText[REDACTED]");
        boolean textEqualsString = text1.equals("hello");
        assertThat(textEqualsString).isFalse();
        assertThat(EncryptedText.valueOf(text1)).isEqualTo("hello");
        assertThat(EncryptedText.of(null)).isNull();
        assertThat(EncryptedText.valueOf(null)).isNull();

        EncryptedText updatedSame = EncryptedText.update(text1, "hello");
        assertThat(updatedSame).isSameAs(text1);
        EncryptedText updatedDiff = EncryptedText.update(text1, "world");
        assertThat(updatedDiff.value()).isEqualTo("world");

        text1.assignBlindIndex("hex123");
        assertThat(text1.blindIndex()).isEqualTo("hex123");

        byte[] raw = new byte[]{1, 2, 3};
        EncryptedBytes bytes1 = EncryptedBytes.of(raw);
        EncryptedBytes bytes2 = EncryptedBytes.of(raw);
        EncryptedBytes bytes3 = EncryptedBytes.of(new byte[]{4, 5});

        assertThat(bytes1)
                .isNotNull()
                .isEqualTo(bytes2)
                .isNotEqualTo(bytes3)
                .hasSameHashCodeAs(bytes2)
                .hasToString("EncryptedBytes[REDACTED]");
        boolean bytesEqualsArray = bytes1.equals(raw);
        assertThat(bytesEqualsArray).isFalse();
        assertThat(EncryptedBytes.valueOf(bytes1)).isEqualTo(raw);
        assertThat(EncryptedBytes.of(null)).isNull();
        assertThat(EncryptedBytes.valueOf(null)).isNull();

        EncryptedBytes bytesUpdatedSame = EncryptedBytes.update(bytes1, raw);
        assertThat(bytesUpdatedSame).isSameAs(bytes1);
        EncryptedBytes bytesUpdatedDiff = EncryptedBytes.update(bytes1, new byte[]{4, 5});
        assertThat(bytesUpdatedDiff.value()).isEqualTo(new byte[]{4, 5});

        bytes1.assignBlindIndex(new byte[]{9, 9});
        assertThat(bytes1.blindIndex()).isEqualTo(new byte[]{9, 9});
    }

