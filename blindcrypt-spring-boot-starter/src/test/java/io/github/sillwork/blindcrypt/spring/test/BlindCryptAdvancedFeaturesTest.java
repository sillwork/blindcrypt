    @Test
    void testVectorizedReEncryptionBinaryUpdates() {
        byte[] fp = new byte[]{1, 2, 3};
        TestDocument doc = new TestDocument("Batch Binary Doc", fp, fp);
        TestDocument saved = documentRepository.saveAndFlush(doc);

        byte[] newEnc = new byte[]{10, 20, 30};
        byte[] newBidx = new byte[]{40, 50, 60};
        VectorizedReEncryptionService.RowUpdate rowUpdate = new VectorizedReEncryptionService.RowUpdate(
                saved.getId(), saved.getVersion(), newEnc, newBidx);

        int updated = reEncryptionService.updateStandardBatch(
                "test_documents", "fingerprint", "fingerprint_bidx", List.of(rowUpdate));
        assertThat(updated).isEqualTo(1);

        // Test empty list and invalid identifier
        List<VectorizedReEncryptionService.RowUpdate> emptyList = List.of();
        assertThat(reEncryptionService.updateStandardBatch("test_documents", "fingerprint", "fingerprint_bidx", emptyList)).isZero();
        List<VectorizedReEncryptionService.RowUpdate> updateList = List.of(rowUpdate);
        assertThatThrownBy(() -> reEncryptionService.updateStandardBatch("invalid;table", "fingerprint", "fingerprint_bidx", updateList))
                .isInstanceOf(IllegalArgumentException.class);
    }

    @Test
    void testEncryptedModelsEqualsAndHashCode() {
        EncryptedText t1 = EncryptedText.of("hello");
        EncryptedText t2 = EncryptedText.of("hello");
        EncryptedText t3 = EncryptedText.of("world");

        assertThat(t1).isEqualTo(t2).hasSameHashCodeAs(t2).isNotEqualTo(t3).isNotEqualTo("string");
        assertThat(t1.toString()).contains("EncryptedText");
        assertThat(t1.value()).isEqualTo("hello");
        assertThat(EncryptedText.valueOf(t1)).isEqualTo("hello");
        assertThat(EncryptedText.valueOf(null)).isNull();

        EncryptedBytes b1 = EncryptedBytes.of(new byte[]{1, 2});
        EncryptedBytes b2 = EncryptedBytes.of(new byte[]{1, 2});
        EncryptedBytes b3 = EncryptedBytes.of(new byte[]{3, 4});

        assertThat(b1).isEqualTo(b2).hasSameHashCodeAs(b2).isNotEqualTo(b3).isNotEqualTo("bytes");
        assertThat(b1.toString()).contains("EncryptedBytes");
        assertThat(b1.value()).isEqualTo(new byte[]{1, 2});
        assertThat(EncryptedBytes.valueOf(b1)).isEqualTo(new byte[]{1, 2});
        assertThat(EncryptedBytes.valueOf(null)).isNull();
    }

    @Test
    void testStartupValidatorRejections() {
        EntityManager mockEm = mock(EntityManager.class);
        Metamodel mockMetamodel = mock(Metamodel.class);
        EntityType mockEntityType = mock(EntityType.class);

        when(mockEm.getMetamodel()).thenReturn(mockMetamodel);

        // Missing entity listener
        doReturn(MissingListenerEntity.class).when(mockEntityType).getJavaType();
        Set<EntityType<?>> entitySet = Set.of(mockEntityType);
        when(mockMetamodel.getEntities()).thenReturn(entitySet);

        BlindIndexStartupValidator validator = new BlindIndexStartupValidator(mockEm);
        assertThatThrownBy(validator::afterSingletonsInstantiated)
                .isInstanceOf(BlindCryptConfigurationException.class)
                .hasMessageContaining("does not register BlindIndexListener");

        // DynamicUpdate entity
        doReturn(DynamicUpdateEntity.class).when(mockEntityType).getJavaType();
        assertThatThrownBy(validator::afterSingletonsInstantiated)
                .isInstanceOf(BlindCryptConfigurationException.class)
                .hasMessageContaining("@DynamicUpdate");

        // ElementCollection entity
        doReturn(ElementCollectionEntity.class).when(mockEntityType).getJavaType();
        assertThatThrownBy(validator::afterSingletonsInstantiated)
                .isInstanceOf(BlindCryptConfigurationException.class)
                .hasMessageContaining("@ElementCollection");
    }

    @Test
    void testQueryMethodValidatorForbiddenPatterns() throws NoSuchMethodException {
        Method directMethod = DummyRepo.class.getMethod("findByEmailBlindIndex", String.class);
        assertThatThrownBy(() -> QueryMethodValidator.validateRepositoryMethod(directMethod, TestUser.class))
                .isInstanceOf(BlindCryptConfigurationException.class)
                .hasMessageContaining("targets internal embeddable properties");

        Method encryptedValueMethod = DummyRepo.class.getMethod("findByEmailEncryptedValue", String.class);
        assertThatThrownBy(() -> QueryMethodValidator.validateRepositoryMethod(encryptedValueMethod, TestUser.class))
                .isInstanceOf(BlindCryptConfigurationException.class)
                .hasMessageContaining("targets internal embeddable properties");

        // Annotations and projections are only rejected on queries the rewriter executes (blind-index predicate)
        PartTree blindIndexTree = new PartTree("findByEmail", TestUser.class);

        Method lockMethod = DummyRepo.class.getMethod("findByEmailWithLock", String.class);
        assertThatCode(() -> QueryMethodValidator.validateRepositoryMethod(lockMethod, TestUser.class))
                .doesNotThrowAnyException();
        assertThatThrownBy(() -> QueryMethodValidator.validateBlindIndexQuery(lockMethod, blindIndexTree, TestUser.class))
                .isInstanceOf(BlindCryptConfigurationException.class)
                .hasMessageContaining("@Lock");

        Method graphMethod = DummyRepo.class.getMethod("findByEmailWithGraph", String.class);
        assertThatThrownBy(() -> QueryMethodValidator.validateBlindIndexQuery(graphMethod, blindIndexTree, TestUser.class))
                .isInstanceOf(BlindCryptConfigurationException.class)
                .hasMessageContaining("@EntityGraph");

        Method hintsMethod = DummyRepo.class.getMethod("findByEmailWithHints", String.class);
        assertThatThrownBy(() -> QueryMethodValidator.validateBlindIndexQuery(hintsMethod, blindIndexTree, TestUser.class))
                .isInstanceOf(BlindCryptConfigurationException.class)
                .hasMessageContaining("@QueryHints");

        Method projectionMethod = DummyRepo.class.getMethod("findByEmailProjection", String.class);
        assertThatThrownBy(() -> QueryMethodValidator.validateBlindIndexQuery(projectionMethod, blindIndexTree, TestUser.class))
                .isInstanceOf(BlindCryptConfigurationException.class)
                .hasMessageContaining("returns CharSequence");

        Method unindexedMethod = DummyRepo.class.getMethod("findBySecretNotes", String.class);
        assertThatThrownBy(() -> QueryMethodValidator.validateRepositoryMethod(unindexedMethod, TestUser.class))
                .isInstanceOf(BlindCryptConfigurationException.class)
                .hasMessageContaining("lacks a @BlindIndex");
    }

