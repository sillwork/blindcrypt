    @Test
    void testAllowPlaintextReadDuringMigration() {
        // Insert an unencrypted legacy plaintext record directly into database
        long legacyId = 99999L;
        jdbcTemplate.update(
                "INSERT INTO test_users (id, version, full_name, email, email_bidx, phone, phone_bidx, registration_no, registration_no_bidx, secret_notes) " +
                "VALUES (?, 0, 'Legacy User', 'legacy@plain.com', 'dummy_hash', '1234567890', 'dummy_hash', 'LEGACY-01', 'dummy_hash', 'unencrypted secret notes')",
                legacyId);

        // When allowPlaintextRead is true, reading does not fail with "Invalid ciphertext header"
        EncryptedStringConverter.setAllowPlaintextRead(true);
        try {
            TestUser legacyUser = userRepository.findById(legacyId).orElseThrow();
            assertThat(legacyUser.getEmail()).isEqualTo("legacy@plain.com");
            assertThat(legacyUser.getSecretNotes()).isEqualTo("unencrypted secret notes");
        } finally {
            EncryptedStringConverter.setAllowPlaintextRead(false);
            jdbcTemplate.update("DELETE FROM test_users WHERE id = ?", legacyId);
        }
    }

